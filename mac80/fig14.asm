;	CREATE A "JUMP VECTOR" USING THE IRP GROUP
	IRP	?LAB,<INITIAL,GET,PUT,FINIS>
	JMP	?LAB	;;GENERATE THE NEXT JUMP
	ENDM
;
;	INDIVIDUAL CASES
INITIAL:
	LXI	H,CHRS
	JMP	ENDCASE
CHRS:	IRP	IS,<A-ROSE,?>
	DB	'&IS is IS&'	;IS IS &IS
	DB	'&IS isn''t is&'
	ENDM
;
GET:	JMP	ENDCASE
;
PUT:	JMP	ENDCASE
;
FINIS:	JMP	ENDCASE
	IRP	?X,<>
	DB	'?x'
	DB	'?X'
	DB	'&?X'
	DB	'&?X&'
	DB	'&&?X&'
	ENDM
ENDCASE:
	RET
	END
